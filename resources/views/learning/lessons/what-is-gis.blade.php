<p>
    <strong>GIS stands for Geographic Information System.</strong>
    GIS is a technology used to collect, store, manage, analyze, and display data related to locations on Earth.
    In simple words, GIS connects <strong>locations, maps, and information</strong> to help us understand places and make better decisions.
</p>

<p>
    For example, a GIS map can show the location of a building along with its address, owner's name, building type, and property tax details.
</p>

<h2>Learning goals</h2>
<ul>
    <li>Understand what the letters in GIS stand for</li>
    <li>Learn how location and information are connected</li>
    <li>Recognise the components that make up a GIS system</li>
</ul>

<div class="note">
    <p style="margin:0"><strong>Note:</strong> GIS connects locations, maps, and information to help us understand places and make better decisions.</p>
</div>

<h2>Understanding the Three Parts of GIS</h2>

<h3>1. Geographic &mdash; Understanding Location</h3>
<p>
    Geographic refers to places, positions, and features on Earth. These include buildings, roads, rivers, land boundaries, and cities.
    GIS uses coordinates and maps to identify where these features are located.
</p>
<p><strong>Example:</strong> Finding the exact location of a school, hospital, or building on a map.</p>

<h3>2. Information &mdash; Understanding Data</h3>
<p>
    Information refers to the details connected to a geographic location. These details are called <em>attributes</em>.
    GIS links these attributes to locations so users can view and analyze the information easily.
</p>
<p><strong>Example:</strong> A building on a map may have the following information:</p>
<ul>
    <li>Building ID</li>
    <li>Address and street name</li>
    <li>Owner's name</li>
    <li>Number of floors</li>
    <li>Building usage</li>
    <li>Property tax details</li>
</ul>
<p>Instead of looking through separate records, users can select a building on the map and view its associated information.</p>

<h3>3. System &mdash; Connecting Everything</h3>
<p>
    A system is a combination of hardware, software, geographic data, and methods that work together to make GIS possible.
    GIS software helps users create maps, manage geographic information, perform analysis, and share results.
</p>
<p>Examples of GIS software include:</p>
<ul>
    <li>QGIS</li>
    <li>ArcGIS</li>
    <li>Google Earth (for viewing and exploring geographic information)</li>
</ul>

<div class="tip">
    <p style="margin:0"><strong>Tip:</strong> Think of GIS as a bridge between a physical location and the data stored about it. The map shows you where it is, and the attributes tell you what it is.</p>
</div>