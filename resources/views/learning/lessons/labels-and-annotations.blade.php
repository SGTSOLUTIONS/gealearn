<p>
    Labels show attribute values on the map. Annotations are manual notes you place yourself.
</p>

<h3>Learning goals</h3>
<ul>
    <li>Add labels from a field</li>
    <li>Improve label readability</li>
    <li>Create manual annotations</li>
</ul>

<h3>Labels vs Annotations</h3>
<div style="display:grid; grid-template-columns:repeat(auto-fit,minmax(200px,1fr)); gap:15px; margin:20px 0;">
    <div style="border:1px solid #245b83; border-radius:8px; overflow:hidden; background:#f5f8fc;">
        <div style="background:#245b83; color:white; padding:12px; font-weight:bold; text-align:center;">Labels (from a field)</div>
        <div style="padding:15px; text-align:center;">
            <p>Automatic · uses an attribute field</p>
            <p><em>Set in: Layer Styling &gt; Labels</em></p>
        </div>
    </div>
    <div style="border:1px solid #198754; border-radius:8px; overflow:hidden; background:#f5f8fc;">
        <div style="background:#198754; color:white; padding:12px; font-weight:bold; text-align:center;">Annotation (manual note)</div>
        <div style="padding:15px; text-align:center;">
            <p>Manual · placed by hand</p>
            <p><em>One-off notes, callouts</em></p>
        </div>
    </div>
</div>

<ul>
    <li>Turn on labels: <strong>Layer Styling</strong> &gt; <strong>Labels</strong> &gt; <strong>Single Labels</strong>, then choose the field.</li>
    <li>Improve readability with a <strong>text buffer</strong> (halo), font size and placement.</li>
    <li>Set <strong>scale-dependent visibility</strong> to avoid clutter when zoomed out.</li>
    <li><strong>Annotations</strong> (Annotations toolbar) hold free text and callouts for one-off notes.</li>
    <li>Labels follow the data automatically; annotations stay where you put them.</li>
</ul>

<div class="tip">
    <p style="margin:0">
        <strong>Practical tip:</strong> Use labels for names and values, annotations for explanations.
    </p>
</div>