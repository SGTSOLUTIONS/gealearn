<p>
    The Print Layout turns your map into a finished page with all the elements a reader needs.
</p>

<h3>Learning goals</h3>
<ul>
    <li>Create a print layout</li>
    <li>Add map elements</li>
    <li>Export or print the final map</li>
</ul>

