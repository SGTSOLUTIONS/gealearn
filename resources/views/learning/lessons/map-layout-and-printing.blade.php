<ul>
    <li>Open with <strong>Project &gt; New Print Layout</strong> (Ctrl+P) and give it a name.</li>
    <li>Add items from the <strong>Add Item</strong> menu: Map, Label, Legend, Scale Bar, North Arrow.</li>
    <li>Set page size and orientation in <strong>Page Properties</strong> (right-click the page).</li>
    <li>Move and resize items by dragging; fine-tune in <strong>Item Properties</strong>.</li>
    <li>A project can store <strong>many layouts</strong> (Project &gt; Layout Manager).</li>
</ul>

<div class="tip">
    <p style="margin:0">
        <strong>Practical tip:</strong> Every map needs: title, map, legend, scale bar and north arrow.
    </p>
