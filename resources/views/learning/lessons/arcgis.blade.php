<h3>Same idea, different names</h3>
<ul>
    <li><strong>Saved work file:</strong> Project (.qgz) in QGIS, Project (.aprx) in ArcGIS Pro</li>
    <li><strong>Data layer:</strong> Layer in QGIS; Layer or feature class in ArcGIS Pro</li>
    <li><strong>Data container:</strong> GeoPackage in QGIS; file geodatabase in ArcGIS Pro</li>
    <li><strong>Map page:</strong> Print Layout in QGIS; Layout in ArcGIS Pro</li>
    <li><strong>Analysis tools:</strong> Processing Toolbox in QGIS; Geoprocessing tools in ArcGIS Pro</li>
</ul>

<p>
    A licence or an Esri account is required to use ArcGIS, and a trial is available
    for learning and evaluation. ArcGIS Pro project files use the .aprx extension,
    so plan for that when moving work between the two platforms.
</p>

<div class="tip">
    <p style="margin:0">
