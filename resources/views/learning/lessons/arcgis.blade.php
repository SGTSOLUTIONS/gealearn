<p>
    ArcGIS is Esri's commercial GIS platform, made of three connected products.
    Its concepts are the same as in QGIS: layers, attribute tables, symbology and
    layouts. Learning the ideas once in QGIS means you can move to ArcGIS Pro
    without relearning the fundamentals.
</p>

<h3>Learning goals</h3>
<ul>
    <li>Know the three ArcGIS products</li>
    <li>Compare ArcGIS Pro with QGIS</li>
    <li>Understand licensing</li>
</ul>

