

<p>
    A Geographic Coordinate System (GCS) is a reference system that uses angular coordinates, primarily latitude and longitude, to identify locations on the Earth's surface. It defines positions relative to a reference model of the Earth, such as an ellipsoid.
</p>

<h2>1. Components of a Geographic Coordinate System</h2>
<ul>
    <li><strong>Latitude:</strong> Measures the angular position of a location north or south of the Equator. Values range from 0° to 90° in either direction.</li>
    <li><strong>Longitude:</strong> Measures the angular position of a location east or west of the Prime Meridian. Values range from 0° to 180° in either direction.</li>
    <li><strong>Datum:</strong> Provides the reference for relating geographic coordinates to the Earth's shape and position.</li>
</ul>

<h2>2. Example of Geographic Coordinates</h2>
<p>A location in Chennai, India, can be represented approximately as:</p>
<ul>
    <li><strong>Latitude:</strong> 13.0827° N</li>
    <li><strong>Longitude:</strong> 80.2707° E</li>
</ul>
<p>
    These coordinates identify a specific location in Chennai. Latitude indicates its position north of the Equator, while longitude indicates its position east of the Prime Meridian.
</p>

<h2>3. Applications of Geographic Coordinate Systems</h2>
<p>Geographic Coordinate Systems are commonly used for:</p>
<ul>
    <li>Recording GPS locations.</li>
    <li>Mapping cities, roads, rivers, and other geographic features.</li>
    <li>Representing locations in satellite imagery.</li>
    <li>Supporting navigation and geographic data collection.</li>
    <li>Storing and exchanging global location data.</li>
</ul>

<h2>4. Key Characteristics</h2>
<ul>
    <li>Uses angular measurements, usually in degrees.</li>
    <li>Represents positions using latitude and longitude.</li>
    <li>References the Earth's surface through a datum and an Earth model.</li>
    <li>Is suitable for representing locations worldwide.</li>
    <li>Does not use a flat map projection to define its coordinates.</li>
</ul>

