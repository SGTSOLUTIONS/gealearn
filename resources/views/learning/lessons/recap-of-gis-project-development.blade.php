<h2>Practice checklist</h2>
<ul>
    <li>Write a one-page goal, scope and requirements list for a small property project.</li>
    <li>Draw the architecture and the ER diagram for it.</li>
    <li>Set up a PostGIS database with parcels, owners and tax tables.</li>
    <li>Build a web map with a layer panel, search and popups.</li>
    <li>Add login with viewer and editor roles and an import tool with a staging table.</li>
    <li>Test it, write the documentation and deploy it to a staging server.</li>
</ul>

