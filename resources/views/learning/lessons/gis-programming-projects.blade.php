<h2>Key Points (Q&A)</h2>
<ul>
    <li><strong>Which projects suit beginners?</strong> CSV to points map, batch reproject, automatic area report.</li>
    <li><strong>Which are intermediate?</strong> Nearest facility finder, zonal statistics per ward, suitability script.</li>
    <li><strong>Which are advanced?</strong> Change-detection pipeline, flood-risk model, web map generator.</li>
    <li><strong>How should I structure a project?</strong> Folder with README, requirements.txt and Git version control.</li>
    <li><strong>How do I build a portfolio?</strong> Publish on GitHub with sample data and screenshots.</li>
    <li><strong>How should I start?</strong> Get a small version working first, then add features.</li>
</ul>

