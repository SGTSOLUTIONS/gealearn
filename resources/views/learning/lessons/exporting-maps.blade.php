<p>
    Exporting saves your map or layout as an image or a PDF, ready to share or print.
    You can export the current map canvas view, or export a finished Print Layout
    with all its elements included.
</p>

<h3>Learning goals</h3>
<ul>
    <li>Export a map layout to an image or PDF</li>
    <li>Export the map canvas view</li>
    <li>Choose the right resolution</li>
    <li>Set a transparent background</li>
</ul>

