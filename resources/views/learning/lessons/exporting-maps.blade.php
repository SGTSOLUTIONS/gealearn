<ul>
    <li>To export a layout: open the Print Layout and use <strong>Layout &gt; Export as Image</strong> or <strong>Export as PDF</strong>.</li>
    <li>To export the map view: use <strong>Project &gt; Import/Export &gt; Export Map to Image</strong>.</li>
    <li>Set the <strong>resolution (DPI)</strong>: use 300 DPI for print quality, 96 DPI for screen use.</li>
    <li>Tick <strong>Save world file</strong> if you want the exported image to keep its geographic position.</li>
    <li>Enable <strong>transparent background</strong> when the map will sit on a coloured page or slide.</li>
</ul>

<div class="tip">
    <p style="margin:0">
        <strong>Practical tip:</strong> Export to PDF for printing, and to PNG for sharing on the web or in documents.
    </p>
