<h2>Key Points (Practice Checklist)</h2>
<ul>
    <li>Run a nearest neighbour analysis and explain whether the points are clustered.</li>
    <li>Interpolate sample points with IDW and compare the surface with a TIN.</li>
    <li>From a DEM extract streams and delineate one watershed.</li>
    <li>Build a suitability map from three scored criteria and one exclusion mask.</li>
    <li>Show a DEM in a 3D map view and extrude building footprints.</li>
    <li>Chain buffer, clip and dissolve in the Graphical Modeler and run it in batch.</li>
</ul>

