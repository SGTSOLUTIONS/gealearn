<h3>Open source and commercial software</h3>
<p>
    Open-source software such as QGIS is free to use, study and share, and is
    developed by a large community. Commercial software such as ArcGIS requires
    a licence or subscription and normally includes vendor support. Both follow
    the same core ideas, so skills transfer between them easily.
</p>

<h3>Which software for which need?</h3>
<ul>
    <li><strong>Learn GIS and analyse data for free:</strong> QGIS</li>
    <li><strong>Share maps and apps across an organisation:</strong> ArcGIS Online or ArcGIS Enterprise</li>
    <li><strong>Collect survey data in the field:</strong> QField or Field Maps</li>
    <li><strong>Automate repeated tasks:</strong> GDAL or GeoPandas in Python</li>
</ul>

