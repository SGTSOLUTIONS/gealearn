<h2>Key Points</h2>
<ul>
    <li><strong>Desktop GIS</strong> – full analysis, editing and map making (QGIS, ArcGIS Pro).</li>
    <li><strong>Web / Server GIS</strong> – publishes maps and data online (GeoServer, ArcGIS Online).</li>
    <li><strong>Mobile GIS</strong> – collects data in the field using phones or tablets.</li>
    <li><strong>Libraries</strong> – code tools for automation (GDAL, GeoPandas).</li>
    <li>Open source software is free; commercial software needs a licence.</li>
</ul>

