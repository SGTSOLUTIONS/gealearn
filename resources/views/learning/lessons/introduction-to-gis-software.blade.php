<h2>Introduction to GIS Software</h2>

<p>
    GIS software is used to create, store, analyse and display spatial data on maps.
    Different kinds of GIS software suit different jobs, from full desktop analysis
    to field data collection. Understanding which type fits a task saves time,
    money and unnecessary workarounds.
</p>

<h3>Learning goals</h3>
<ul>
    <li>Recognise the main types of GIS software</li>
    <li>Know examples of each type</li>
    <li>Understand open source versus commercial software</li>
</ul>

