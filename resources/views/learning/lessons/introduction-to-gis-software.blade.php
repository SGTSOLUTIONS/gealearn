<p>
    GIS software is used to create, store, analyse, and display spatial data on maps.
    Different types of GIS software serve different purposes, from full desktop analysis to code-based automation.
</p>

<h2>Learning goals</h2>
<ul>
    <li>Understand the four main categories of GIS software</li>
    <li>Recognise the difference between open-source and commercial software</li>
    <li>Identify tools for desktop, web, mobile, and library environments</li>
</ul>

