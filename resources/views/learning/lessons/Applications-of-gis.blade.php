<p>
    GIS (Geographic Information System) is used in many industries because location helps us understand people, infrastructure, natural resources, and the environment.
    GIS connects maps with useful information, allowing people to analyze data, identify problems, and make better decisions.
</p>

<h2>Learning goals</h2>
<ul>
    <li>Discover how GIS is used in different industries</li>
    <li>Understand real-world applications of spatial analysis</li>
    <li>Recognise the value of GIS in planning and management</li>
</ul>

<div class="note">
    <p style="margin:0"><strong>Note:</strong> GIS is not limited to creating maps. It can also be used to identify suitable locations, measure distances, monitor environmental changes, manage land records, plan transportation networks, and support decision-making.</p>
</div>

<h2>1. Geography and Social Sciences</h2>
<p>GIS helps us understand how people live, where they move, and how communities develop.</p>
<p><strong>Applications:</strong></p>
<ul>
    <li>Mapping population distribution and population growth.</li>
    <li>Studying migration and settlement patterns.</li>
    <li>Identifying areas with limited access to schools, hospitals, and public services.</li>
    <li>Understanding regional development.</li>
</ul>

<div class="example">
    <h2>Example</h2>
    <p>A government uses GIS to identify areas that need more schools or healthcare facilities.</p>
</div>

<h2>2. Economics</h2>
<p>GIS helps businesses and governments understand economic activities and differences between locations.</p>
<p><strong>Applications:</strong></p>
<ul>
    <li>Identifying suitable locations for businesses.</li>
    <li>Mapping employment and economic growth.</li>
    <li>Studying transportation accessibility.</li>
    <li>Comparing economic development between regions.</li>
    <li>Identifying areas with unequal access to jobs and services.</li>
</ul>

<div class="example">
    <h2>Example</h2>
    <p>A company uses GIS to find a suitable location for a new supermarket based on population, roads, and nearby competitors.</p>
</div>

<h2>3. History and Archaeology</h2>
<p>GIS helps researchers study historical places, ancient settlements, and changes in landscapes over time.</p>
<p><strong>Applications:</strong></p>
<ul>
    <li>Mapping archaeological sites and historical monuments.</li>
    <li>Studying ancient trade routes and settlements.</li>
    <li>Mapping historical boundaries.</li>
    <li>Comparing old maps with modern maps.</li>
    <li>Monitoring changes around heritage sites.</li>
</ul>

<div class="example">
    <h2>Example</h2>
    <p>Archaeologists use GIS to map ancient settlements and study their relationship with rivers and historical trade routes.</p>
</div>

<h2>4. Geology and Mining</h2>
<p>GIS helps geologists study the Earth's surface, rock formations, and mineral resources.</p>
<p><strong>Applications:</strong></p>
<ul>
    <li>Mapping rock formations and geological structures.</li>
    <li>Identifying mineral resource locations.</li>
    <li>Mapping faults and geological hazards.</li>
    <li>Supporting mineral exploration.</li>
    <li>Monitoring mining areas and land changes.</li>
</ul>

<div class="example">
    <h2>Example</h2>
    <p>A mining company uses GIS to analyze geological maps and identify areas that may be suitable for mineral exploration.</p>
</div>

<h2>5. Agriculture</h2>
<p>GIS helps farmers and agricultural organizations monitor crops, manage farmland, and use resources efficiently.</p>
<p><strong>Applications:</strong></p>
<ul>
    <li>Mapping agricultural land and soil types.</li>
    <li>Monitoring crop growth and vegetation health.</li>
    <li>Planning irrigation systems.</li>
    <li>Identifying suitable land for different crops.</li>
    <li>Monitoring drought and crop damage.</li>
</ul>

<div class="example">
    <h2>Example</h2>
    <p>A farmer uses GIS and satellite imagery to identify parts of a field where crops may need more water.</p>
</div>

<h2>6. Environmental Management</h2>
<p>GIS helps monitor natural resources and understand changes in the environment.</p>
<p><strong>Applications:</strong></p>
<ul>
    <li>Mapping forests, wetlands, and wildlife habitats.</li>
    <li>Monitoring deforestation and land degradation.</li>
    <li>Studying pollution and environmental changes.</li>
    <li>Identifying areas important for biodiversity.</li>
    <li>Supporting conservation planning.</li>
</ul>

<div class="example">
    <h2>Example</h2>
    <p>Environmental researchers compare satellite images from different years to identify areas where forest cover has decreased.</p>
</div>

<h2>7. Water Resources</h2>
<p>GIS helps manage water resources and understand how water moves across the landscape.</p>
<p><strong>Applications:</strong></p>
<ul>
    <li>Mapping rivers, lakes, and reservoirs.</li>
    <li>Mapping drainage networks and watersheds.</li>
    <li>Identifying groundwater resource areas.</li>
    <li>Studying flood-prone locations.</li>
    <li>Planning water supply and irrigation systems.</li>
</ul>

<div class="example">
    <h2>Example</h2>
    <p>A local authority uses GIS to map drainage channels and identify neighborhoods that may be at risk of flooding.</p>
</div>

<h2>8. Urban Planning</h2>
<p>GIS helps planners manage cities, develop infrastructure, and organize land use.</p>
<p><strong>Applications:</strong></p>
<ul>
    <li>Mapping roads, buildings, and land parcels.</li>
    <li>Planning residential, commercial, and industrial areas.</li>
    <li>Identifying suitable locations for schools and hospitals.</li>
    <li>Monitoring urban growth.</li>
    <li>Analyzing road networks and infrastructure needs.</li>
</ul>

<div class="example">
    <h2>Example</h2>
    <p>A city planning department uses GIS to identify areas where new roads or public facilities may be needed.</p>
</div>

<h2>9. Disaster Management</h2>
<p>GIS helps authorities prepare for disasters, assess risks, and coordinate emergency responses.</p>
<p><strong>Applications:</strong></p>
<ul>
    <li>Mapping flood-prone areas and landslide risks.</li>
    <li>Identifying vulnerable communities.</li>
    <li>Planning evacuation routes.</li>
    <li>Mapping emergency shelters and hospitals.</li>
    <li>Assessing damage after natural disasters.</li>
</ul>

<div class="example">
    <h2>Example</h2>
    <p>During a flood, emergency teams use GIS maps to identify affected neighborhoods and plan safer routes for rescue operations.</p>
</div>

<h2>10. Government and Public Administration</h2>
<p>GIS helps government departments manage land records, public assets, infrastructure, and municipal services.</p>
<p><strong>Applications:</strong></p>
<ul>
    <li>Mapping property boundaries and land records.</li>
    <li>Managing property tax and assessment information.</li>
    <li>Mapping public assets such as buildings and streetlights.</li>
    <li>Managing water supply, drainage, and road networks.</li>
    <li>Supporting municipal planning and public service delivery.</li>
</ul>

<div class="example">
    <h2>Example</h2>
    <p>A municipality uses GIS to display building locations, link them to property tax records, and identify properties that may require assessment.</p>
</div>

<p>This is particularly useful for municipal surveys, where building boundaries, geographic coordinates, property details, and tax records can be managed together on a digital map.</p>

<div class="tip">
    <p style="margin:0"><strong>Tip:</strong> GIS helps organisations make better decisions, plan efficiently, manage resources, protect the environment, assess risks, and save time and costs.</p>
</div>