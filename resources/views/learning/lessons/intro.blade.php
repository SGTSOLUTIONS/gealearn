<h2>Practical Exercise</h2>
<p>Choose your college, school, or neighbourhood. Identify five geographic features, such as roads, buildings, a water body, a park, and a hospital. Decide which features should be represented as points, lines, or polygons. Then list three questions that could be answered by analysing these features on a map.</p>