<h1>GIS Tutorial</h1>

<p>
    Welcome to the GIS Tutorial. This is your starting point for learning Geographic Information Systems (GIS) from the basics to advanced applications. 
    This tutorial is designed for students, teachers, researchers, engineers, planners, and anyone interested in understanding how geographic data can be collected, managed, analyzed, and presented using digital maps.
</p>

<p>
