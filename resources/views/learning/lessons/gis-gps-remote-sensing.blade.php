<p>
    GIS, GPS, and Remote Sensing are three related technologies used to collect, locate, and analyze geographic information. However, each has a different purpose.
</p>

<h2>Learning goals</h2>
<ul>
    <li>Understand the difference between GIS, GPS, and Remote Sensing</li>
    <li>Learn the main purpose of each technology</li>
    <li>See how they work together in a real-world workflow</li>
</ul>

<div class="note">
    <p style="margin:0"><strong>Note:</strong> GIS manages and analyzes geographic information, GPS finds a location, and Remote Sensing collects information from a distance.</p>
</div>

<h2>1. What Is the Difference?</h2>

<table>
    <thead>
        <tr>
            <th>Technology</th>
            <th>Main Purpose</th>
            <th>Example</th>
        </tr>
    </thead>
    <tbody>
        <tr>
            <td><strong>GIS</strong> (Geographic Information System)</td>
            <td>Stores, manages, analyzes, and displays geographic data on maps.</td>
            <td>Mapping buildings and managing property tax records.</td>
        </tr>
        <tr>
            <td><strong>GPS</strong> (Global Positioning System)</td>
            <td>Finds the geographic location of a person or object using satellite signals.</td>
            <td>Recording the location of a building during a field survey.</td>
        </tr>
        <tr>
            <td><strong>Remote Sensing</strong></td>
            <td>Collects information about Earth's surface from a distance using satellites, drones, or aircraft.</td>
            <td>Using satellite images to monitor forests.</td>
        </tr>
    </tbody>
</table>

<h2>2. How Do They Work Together?</h2>
<p>GIS, GPS, and Remote Sensing can be used together to solve real-world problems.</p>

<div class="example">
    <h2>Example: Mapping Buildings in a Municipality</h2>
    <ol>
        <li><strong>GPS:</strong> Collects the coordinates of buildings during a field survey.</li>
        <li><strong>Remote Sensing:</strong> Provides satellite or drone images showing buildings and surrounding areas.</li>
        <li><strong>GIS:</strong> Combines the coordinates, images, and property records to create a map and analyze the information.</li>
    </ol>
</div>

<h2>3. Remember the Difference</h2>
<ul>
    <li><strong>GIS:</strong> Manages and analyzes geographic information.</li>
    <li><strong>GPS:</strong> Finds a location.</li>
    <li><strong>Remote Sensing:</strong> Collects information from a distance.</li>
</ul>

<div class="tip">
    <p style="margin:0"><strong>Tip:</strong> A surveyor can use GPS to record the location of a land parcel, remote sensing to obtain aerial or satellite imagery, and GIS to combine the information and analyze the parcel's characteristics.</p>
</div>