<p>
    Navigation tools move around the map and change the visible area, called the extent.
</p>

<h3>Learning goals</h3>
<ul>
    <li>Pan and zoom efficiently</li>
    <li>Use keyboard shortcuts</li>
    <li>Set an exact map scale</li>
</ul>

<h3>Navigation shortcuts</h3>
<div style="border-radius:8px; overflow:hidden; margin:15px 0;">
    <table style="width:100%; border-collapse:collapse; font-size:14px;">
        <tr style="background:#eef3f8;">
            <th style="padding:10px; text-align:left;">Tool</th>
            <th style="padding:10px; text-align:left;">Shortcut / Action</th>
        </tr>
        <tr><td style="padding:10px;">Pan</td><td style="padding:10px;">Space or middle mouse button</td></tr>
        <tr><td style="padding:10px;">Zoom In / Out</td><td style="padding:10px;">Mouse scroll wheel</td></tr>
        <tr><td style="padding:10px;">Zoom Full</td><td style="padding:10px;">Ctrl+Shift+F</td></tr>
        <tr><td style="padding:10px;">Zoom to Selection</td><td style="padding:10px;">Ctrl+J</td></tr>
        <tr><td style="padding:10px;">Scale box</td><td style="padding:10px;">type a value such as 1:5000</td></tr>
    </table>
</div>

<ul>
    <li>Zoom tools also allow a drag box.</li>
    <li>Zoom Full shows all layers at once.</li>
    <li>Zoom to Layer or Selection jumps straight to your data.</li>
    <li>Zoom Last and Next step through earlier views.</li>
</ul>

<h3>Typical scales</h3>
<ul>
    <li>1:500 – buildings and street detail</li>
    <li>1:5,000 – a neighbourhood</li>
    <li>1:50,000 – a town or city</li>
    <li>1:1,000,000 – a country or region</li>
</ul>

<h3>Spatial bookmarks</h3>
<p>
    Press <code>Ctrl+B</code> to save the current view as a bookmark and <code>Ctrl+Shift+B</code> to show the saved bookmarks.
</p>

<div class="tip">
    <p style="margin:0">
        <strong>Practical tip:</strong> Lost on a blank canvas? Press Zoom Full or right-click the layer &gt; Zoom to Layer(s).
    </p>
</div>