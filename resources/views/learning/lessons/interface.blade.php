<p>
    The QGIS window is divided into areas. Each area has one clear job, so knowing
    where things live makes every later topic easier. If a panel disappears, it can
    always be brought back from the View menu.
</p>

<h3>Learning goals</h3>
<ul>
    <li>Identify the main QGIS panels</li>
    <li>Know where tools and commands live</li>
    <li>Recover a missing panel</li>
</ul>

<h3>Main areas of the QGIS window</h3>
<ul>
    <li><strong>Menu bar and toolbars</strong> – commands such as Project, Layer, Vector and Raster.</li>
    <li><strong>Browser panel</strong> – finds files and databases on your computer.</li>
    <li><strong>Layers panel</strong> – lists, orders and shows or hides layers.</li>
    <li><strong>Map canvas</strong> – the area where your data is displayed.</li>
    <li><strong>Processing Toolbox</strong> – a searchable list of analysis tools.</li>
    <li><strong>Status bar</strong> – shows coordinates, scale, rotation and the project CRS.</li>
</ul>

