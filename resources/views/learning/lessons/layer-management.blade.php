<h2>Key Points</h2>
<ul>
    <li>Rename a layer: select it and press <strong>F2</strong>. Use clear names.</li>
    <li>Group related layers (right-click > Group Selected) to keep the panel tidy.</li>
    <li><strong>Zoom to Layer, Duplicate, and Move to Top</strong> are in the right-click menu.</li>
    <li><strong>Export > Save Features As</strong> writes a new file – use it to change format or CRS.</li>
    <li><strong>Remove Layer</strong> only removes it from the project, not from your disk.</li>
    <li>Temporary scratch layers (memory icon) vanish unless you save them.</li>
</ul>

