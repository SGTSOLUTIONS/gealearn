<p>
    Layer management keeps a project organised: naming, grouping, ordering, and exporting.
    Good management saves time and prevents mistakes when working with many datasets.
</p>

<h2>Learning goals</h2>
<ul>
    <li>Rename and group layers effectively</li>
    <li>Understand the difference between removing and deleting</li>
    <li>Export layers to new formats</li>
</ul>

