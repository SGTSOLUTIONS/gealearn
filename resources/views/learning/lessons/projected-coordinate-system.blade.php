
<p>
    A Projected Coordinate System (PCS) represents geographic locations on a flat, two-dimensional map using a map projection. Coordinates are commonly expressed as eastings and northings, measured in metres or feet.
</p>

<h2>Projected Coordinates: Easting and Northing</h2>
<ul>
    <li><strong>Easting:</strong> Represents a position in the east–west direction on the projected grid.</li>
    <li><strong>Northing:</strong> Represents a position in the north–south direction on the projected grid.</li>
</ul>
<p>
    These coordinates help identify locations and measure distances on a map.
</p>

<h2>How Does a Projected Coordinate System Work?</h2>
<p>
    A map projection transforms geographic positions from the Earth's curved surface onto a flat map. This allows GIS software to represent locations using grid coordinates.
</p>
<p>
    Because the Earth is curved, every map projection introduces some distortion in properties such as distance, area, shape, or direction.
</p>

<h2>Applications of Projected Coordinate Systems</h2>
<ul>
    <li>Measuring distances between locations.</li>
    <li>Calculating land areas.</li>
    <li>Mapping roads and infrastructure.</li>
    <li>Planning urban development.</li>
    <li>Conducting spatial analysis.</li>
</ul>