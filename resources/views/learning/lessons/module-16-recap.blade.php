<h2>Practice checklist</h2>
<ul>
    <li>Make a project map with a base map, two layers and a saved style.</li>
    <li>Turn a CSV into points and count them per ward with a spatial join.</li>
    <li>Calculate parcel areas in hectares and make a choropleth map of one ward value.</li>
    <li>Publish a PostGIS layer through GeoServer and show it in an OpenLayers page.</li>
    <li>Extrude building footprints in a 3D viewer.</li>
    <li>Combine the results into a small dashboard and write a short README.</li>
</ul>

