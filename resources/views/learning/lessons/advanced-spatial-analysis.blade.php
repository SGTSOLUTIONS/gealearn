<h2>Key Points (Q&A)</h2>
<ul>
    <li><strong>What does advanced analysis add?</strong> It moves from "what is here?" to "why, how much and what next?": patterns, predictions, models and decisions.</li>
    <li><strong>Which methods does this module cover?</strong> Statistics, interpolation, hydrology, suitability and MCDA, 3D, time series, automation and web delivery.</li>
    <li><strong>What must the data be like first?</strong> Clean, valid and in a correct CRS (Module 4). Results are only as good as the input.</li>
    <li><strong>Which tools are used?</strong> QGIS Processing providers (native, GDAL, GRASS), plugins and Python libraries.</li>
    <li><strong>How do I check a result?</strong> Test on a small area first, compare with known facts and record every parameter used.</li>
</ul>

<div class="tip">
    <p style="margin:0"><strong>Tip:</strong> Choose the method by the question you need answered, not by the tool you already know.</p>
