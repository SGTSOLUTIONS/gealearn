<h2>Key Points (Practice Checklist)</h2>
<ul>
    <li>Install QGIS and identify the main interface areas.</li>
    <li>Create a project, set its CRS and save it in a clean folder.</li>
    <li>Load a shapefile and a CSV; reorder, rename and group the layers.</li>
    <li>Open the attribute table, select features by expression and by location.</li>
    <li>Measure a distance and an area; use zoom and pan shortcuts.</li>
    <li>Style by category, add labels, build a layout and export it as PDF.</li>
</ul>

